//! The 128-entry table behind `ln_dd` (the logarithm `pow` uses).
//!
//! `x = 2^k z` with `z` in `[OFF, 2 OFF)`; the top seven bits of `bits(x) - OFF` below the
//! exponent pick bucket `i`. Row `i` is `(1/c, ln c hi, ln c lo)`: `1/c` has at most 21
//! significant bits (so `z_hi * (1/c)` and `z_lo * (1/c)` are exact products, no FMA
//! needed), and `ln c` is a double-double to ~2^-106. `OFF` puts 1.0 at the *centre* of
//! bucket [`LN_TABLE_ONE`], whose `1/c` is exactly 1 and `ln c` exactly 0.
//!
//! Every row is re-derived on every test run from the rule in `det::tests::ln_table_rule`
//! (bucket centres, then `ln` by a bignum atanh series). Regenerate with
//! `cargo test -p forge-num --lib print_ln_table -- --ignored --nocapture`.

