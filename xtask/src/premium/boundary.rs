//! `cargo xtask premium-boundary` — the open-core boundary holds (ADR 0059, E-66).
//!
//! Over every workspace member and every repository file, with `premium.ron` saying what is
//! premium:
//!
//! * **P1.** A base member never depends on a premium crate — in `[dependencies]`,
//!   `[dev-dependencies]` or `[build-dependencies]`, any target. Otherwise the export could
//!   not build it.
//! * **P2.** A base file never names a premium identifier (a premium crate name in either
//!   spelling, a premium path, a listed type/module/tool name, or a premium DoD id, gate row
//!   or error code, a range citation spanning one included), in its path or its text.
//!   Checked on what the export would write: `tests/gates.ron` without its premium rows and
//!   the workspace `Cargo.toml` without its premium tables. Markdown and `dod-status.ron`
//!   are not checked here: the export scrubs them ([`super::scrub`]) and leak-scans the
//!   result. `Cargo.lock` is regenerated by the export.
//! * **P3.** A premium path never sits inside a base member (premium code lodged in a base
//!   crate).
//! * **P4.** A base member never declares a premium cargo feature.
//! * **P5.** `premium.ron` is exact: each premium crate exists under its name, each premium
//!   path exists, each marked doc section is marked exactly once, each premium DoD id, gate
//!   row and error code exists, each rewrite still matches.
//!
//! P1-P3 violations that exist today are **debt**, listed in `premium_debt.ron`, each with the
//! work package that removes it (WP-42, WP-43, WP-44; `premium.ron` says what each moved). The debt list is exact (a listed violation
//! that no longer exists is an error: delete the line), and it **only shrinks**: its size
//! must equal [`DEBT_CEILING`], which may only go down, and never above [`DEBT_AT_WP41`].
//! `cargo xtask premium-boundary --write-debt` rewrites the debt file to what is still true
//! (it never adds an entry once the file exists) and prints the new ceiling.
//!
//! [`DEBT_AT_WP41`] is the baseline drawn by WP-41 and is never raised: a change that raises
//! it (or [`DEBT_CEILING`] above it) grows the debt, which a reviewer rejects.
//!
//! A repository without `premium.ron` (the public export) has nothing premium to separate
//! and says so, unless it still has a debt file or a non-zero ceiling: then the manifest was
//! lost, and the check fails ([`no_manifest`]).

