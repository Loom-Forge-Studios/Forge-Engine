/// The size of `premium_debt.ron` (dependency edges + identifiers named + lodged paths).
/// **Lower it** in the change that burns debt down (the check requires it to equal the debt's
/// size, so it cannot be forgotten). **Never raise it**: a new premium name in a base file is
/// a boundary violation to fix, not debt to record.
///
/// Raised from 558 to 559 by the WP-41 integrate step: `dev` had moved ahead with WP-U20
/// (scene composition, ADR 0058) before this boundary existed there, and one of its guard
/// tests drives the real agent-protocol server, lodged in the base `forge-editor` crate
/// exactly like the other WP-42 items above. This is the one violation WP-U20's code added
/// that a wording fix could not remove (its two other new premium mentions were reworded,
/// and its UI test's agent-issued command swapped for a script-issued one, without touching
/// this test's real agent-protocol integration) — see `premium.ron`'s `paths` entry and
/// `premium_debt.ron`'s `lodged` entry, both under WP-42, for the test file itself.
///
/// Lowered from 559 to 248 by WP-43 (ADR 0060) and WP-42 (ADR 0061) together: the frame
/// stack left the base (every WP-43 entry, and three WP-44 mentions of a premium crate in
/// the text it rewrote), and every WP-42 entry is gone (the base crates' dependency edges,
/// the names and the lodged test). Only WP-44 debt remains.
///
/// Lowered from 248 to 0 by WP-44 (ADR 0062): the last premium items left the base, and no
/// base file names a premium identifier or a code term (`premium.ron`'s `code_terms`, which
/// catch premium text a rename would hide). The debt is empty: every boundary violation from
/// now on is an error to fix, never debt.
pub const DEBT_CEILING: usize = 0;

/// The debt when the boundary was drawn (WP-41). [`DEBT_CEILING`] never exceeds it.
///
/// Raised from 558 to 559 alongside `DEBT_CEILING` for the same reason (WP-41 integrate
/// step, WP-U20's one new unavoidable violation) — see `DEBT_CEILING`.
pub const DEBT_AT_WP41: usize = 559;

